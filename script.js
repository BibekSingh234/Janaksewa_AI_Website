function getSelectedLanguage() {
    const saved = localStorage.getItem('janaksewaLang');
    if (saved && translations[saved]) {
        return saved;
    }
    const select = document.querySelector('.language-select, #languageSelect');
    return select ? select.value : 'en';
}

function applyTranslations(language) {
    const selected = translations[language] ? language : 'en';
    localStorage.setItem('janaksewaLang', selected);
    document.documentElement.lang = ['ne', 'hi', 'mai'].includes(selected) ? 'hi' : 'en';

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        const values = translations[selected];
        const text = values[key];
        if (text) {
            element.textContent = text;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        const values = translations[selected];
        const text = values[key];
        if (text) {
            element.placeholder = text;
        }
    });

    document.querySelectorAll('.language-select, #languageSelect').forEach((select) => {
        if (select.value !== selected) {
            select.value = selected;
        }
    });
}

function bindSearchControls() {
    const searchButton = document.getElementById('searchButton');
    const searchOverlay = document.getElementById('searchOverlay');
    const websiteSearch = document.getElementById('websiteSearch');
    const closeSearch = document.getElementById('closeSearch');
    const performSearch = document.getElementById('performSearch');

    if (!searchButton || !searchOverlay || !websiteSearch) {
        return;
    }

    searchButton.addEventListener('click', function () {
        searchOverlay.classList.add('show');
        setTimeout(function () {
            websiteSearch.focus();
        }, 200);
    });

    if (closeSearch) {
        closeSearch.addEventListener('click', function () {
            searchOverlay.classList.remove('show');
        });
    }

    searchOverlay.addEventListener('click', function (event) {
        if (event.target === searchOverlay) {
            searchOverlay.classList.remove('show');
        }
    });

    if (performSearch) {
        performSearch.addEventListener('click', function () {
            const value = websiteSearch.value.trim();
            if (!value) {
                alert(translations[getSelectedLanguage()].searchPrompt || 'Please enter something to search.');
                return;
            }

            const matches = [];
            document.querySelectorAll('h1, h2, h3, h4, h5, h6, p, a, li, span, button, label').forEach((element) => {
                const text = element.textContent.trim();
                if (text && text.toLowerCase().includes(value.toLowerCase())) {
                    matches.push(element);
                }
            });

            if (!matches.length) {
                alert(translations[getSelectedLanguage()].noResults || 'No matching result found.');
                return;
            }

            matches[0].scrollIntoView({ behavior: 'smooth', block: 'start' });
            searchOverlay.classList.remove('show');
        });
    }

    websiteSearch.addEventListener('keydown', function (event) {
        if (event.key === 'Enter' && performSearch) {
            performSearch.click();
        }
    });
}

function bindAnchorScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(function (link) {
        link.addEventListener('click', function (event) {
            const targetId = this.getAttribute('href');
            if (!targetId || targetId === '#') {
                return;
            }

            const target = document.querySelector(targetId);
            if (!target) {
                return;
            }

            event.preventDefault();
            target.scrollIntoView({ behavior: 'smooth', block: 'start' });

            const navbar = document.querySelector('.navbar-collapse');
            if (navbar && navbar.classList.contains('show')) {
                const toggle = document.querySelector('.navbar-toggler');
                if (toggle) {
                    toggle.click();
                }
            }
        });
    });
}

function bindNavActiveState() {
    const navLinks = document.querySelectorAll('.nav-link');
    navLinks.forEach(function (link) {
        link.addEventListener('click', function () {
            navLinks.forEach(function (item) {
                item.classList.remove('active');
            });
            this.classList.add('active');
        });
    });
}


function getApiBase() {
    const isLocalFrontend = window.location.protocol === 'file:'
        || (['localhost', '127.0.0.1'].includes(window.location.hostname)
            && window.location.port !== '8000');
    return isLocalFrontend ? 'http://127.0.0.1:8000' : window.location.origin;
}

function bindContactForm() {
    const form = document.getElementById('contactForm');
    if (!form) return;

    form.addEventListener('submit', async function (event) {
        event.preventDefault();
        const button = form.querySelector('button[type="submit"]');
        const original = button ? button.innerHTML : '';
        if (button) {
            button.disabled = true;
            button.innerHTML = '<i class="fa-solid fa-spinner fa-spin me-2"></i>Sending...';
        }

        const payload = Object.fromEntries(new FormData(form).entries());
        try {
            const csrf = document.cookie.match(/(?:^|; )csrftoken=([^;]+)/);
            if (!csrf) await fetch(`${getApiBase()}/api/csrf/`, { credentials: 'include' });
            const token = (document.cookie.match(/(?:^|; )csrftoken=([^;]+)/) || [])[1] || '';

            const response = await fetch(`${getApiBase()}/api/contact/`, {
                method: 'POST',
                credentials: 'include',
                headers: { 'Content-Type': 'application/json', 'X-CSRFToken': decodeURIComponent(token) },
                body: JSON.stringify(payload)
            });
            const data = await response.json();
            if (!response.ok || !data.success) throw new Error(data.message || 'Unable to send your message.');
            alert(data.message || 'Your message has been sent successfully.');
            form.reset();
        } catch (error) {
            alert(error.message || 'Unable to send your message. Please try again.');
        } finally {
            if (button) {
                button.disabled = false;
                button.innerHTML = original;
            }
        }
    });
}

function init() {
    bindSearchControls();
    bindContactForm();
    bindAnchorScroll();
    bindNavActiveState();

    document.querySelectorAll('.language-select, #languageSelect').forEach((select) => {
        select.addEventListener('change', function () {
            applyTranslations(this.value);
        });
    });

    applyTranslations(getSelectedLanguage());
}

window.translations = translations;
window.getSelectedLanguage = getSelectedLanguage;
window.applyTranslations = applyTranslations;

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
} else {
    init();
}


